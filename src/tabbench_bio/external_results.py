VIEW_START = "<!-- External Elo controls -->"
VIEW_END = "<!-- End external Elo controls -->"


@dataclass(frozen=True)
class ExternalEvaluation:
    model: str
    provenance: str
    classification_only: bool
    source: Path
    cell: str
    config: dict
    datasets: set[str]
    scores: pd.DataFrame


def _cell_config(db, cell):
    row = db.execute("SELECT config_json FROM cells WHERE cell=?", (cell,)).fetchone()
    if row is None:
        raise ValueError(f"Missing cell {cell} in results database")
    return json.loads(row[0])


def _read_quickstart_scores(source, reference, truth, expected):
    manifest = json.loads((source / "split_manifest.json").read_bytes())["units"]
    for seed, key in sorted(expected):
        digest = hashlib.sha256(read_result_blob(reference, truth[seed, key])).hexdigest()
        if manifest.get(unit_id(seed, key), {}).get("ground_truth_sha256") != digest:
            raise ValueError(f"Held-out targets differ from Random Forest at {(seed, key)}")
    metrics = pd.read_csv(
        source / "fold_metrics.csv",
        float_precision="round_trip",
        keep_default_na=False,
        dtype={"key": str, "model": str},
        na_values={"f1_macro": [""]},
    )
    statuses = pd.read_csv(
        source / "attempts.csv", keep_default_na=False, dtype={"key": str, "model": str}
    )
    return metrics, statuses, "Benchmark My Model · submitted Macro-F1"


def _read_sqlite_scores(external, cell, datasets, models, expected, truth, provenance):
    attempts = [
        row
        for row in external.execute(_CURRENT_SQLITE_ATTEMPTS, (cell,))
        if (row[0], row[1]) in expected and row[2] in models
    ]
    statuses = pd.DataFrame(
        [(seed, key, model, status) for seed, key, model, status, *_ in attempts],
        columns=["seed", "key", "model", "status"],
    )
    reported = []
    for seed, key, model, status, _, prediction, _, digest, record in attempts:
        if (digest or status == "pass") and digest != truth[seed, key]:
            raise ValueError(f"Held-out targets differ from Random Forest at {(seed, key)}")
        if provenance is None or status != "pass":
            continue
        if prediction:
            raise ValueError(f"Score-only submission also contains predictions at {(seed, key)}")
        read_result_blob(external, digest)
        attempt = json.loads(unpack_attempt_record(record))
        if attempt.get("task_type") != "classification":
            raise ValueError(f"Invalid reported classification task at {(seed, key)}")
        reported.append((seed, key, model, attempt.get("reported_metrics", {}).get("f1_macro")))
    if provenance is None:
        _, metrics, _ = _metrics_from_sqlite(external, cell, datasets=sorted(datasets))
        return metrics, statuses, "External run · scored from predictions"
    gpu = provenance.get("hardware", {}).get("gpu")
    if not isinstance(gpu, str) or not gpu.strip():
        raise ValueError("External score-only provenance must name the GPU")
    metrics = pd.DataFrame(reported, columns=["seed", "key", "model", "f1_macro"])
    return metrics, statuses, f"{gpu} · author-reported"


def load_external_evaluations(
    database: Path, sources: Sequence[Path], cell: str
) -> list[ExternalEvaluation]:
    """Read registered results, score-only bundles, or quickstart evaluation directories."""
    evaluations = []
    with closing(_open_results_sqlite(database.resolve())) as reference:
        _validate_results_sqlite(reference, database)
        primary = _cell_config(reference, cell)
        truth = {
            (seed, key): digest
            for seed, key, model, status, _, _, _, digest, _ in reference.execute(
                _CURRENT_SQLITE_ATTEMPTS, (cell,)
            )
            if model == "RF" and status == "pass" and digest
        }
        seeds = get_seeds(primary)
        eligible = {
            dataset
            for dataset in set(primary["datasets_classification"])
            - set(primary["exclude_datasets"])
            if all((seed, f"{dataset}_0") in truth for seed in seeds)
        }
        seen = {"DUMMY", *primary["models"]}
        for source in sources:
            source = source.resolve()
            directory = source.is_dir()
            with ExitStack() as stack:
                if directory:
                    contributed = json.loads((source / "config.json").read_bytes())
                    report = json.loads((source / "report/report_config.json").read_bytes())
                    if report["cell"] != cell or report["task"] not in {
                        "classification",
                        "overall",
                    }:
                        raise ValueError(
                            f"Evaluation must cover classification in {cell}: {source}"
                        )
                    models = [report["name"]]
                    contributed.update(
                        models=models, model_limits={}, model_overrides={}, model_tuning={}
                    )
                    provenance = None
                else:
                    external = stack.enter_context(closing(_open_results_sqlite(source)))
                    _validate_results_sqlite(external, source)
                    contributed = _cell_config(external, cell)
                    metadata = dict(external.execute("SELECT key, value FROM metadata"))
                    provenance = json.loads(metadata.get("external_provenance", "null"))
                    models = [model for model in contributed["models"] if model != "DUMMY"]
                    if provenance is not None and (
                        not isinstance(provenance, dict)
                        or provenance.get("task") != "classification"
                        or provenance.get("cell") != cell
                        or models != [provenance.get("model")]
                    ):
                        raise ValueError(f"Invalid external classification provenance: {source}")
                _merge_cell_config(primary, contributed, cell)
                datasets = eligible.intersection(contributed["datasets_classification"]) - set(
                    contributed["exclude_datasets"]
                )
                if not datasets or not models:
                    raise ValueError(f"No shared classification evaluation in {cell}: {source}")
                expected = {(seed, f"{dataset}_0") for seed in seeds for dataset in datasets}
                for model in models:
                    if not isinstance(model, str) or not model.strip():
                        raise ValueError(f"Invalid external model name: {source}")
                    if (
                        model in seen
                        or reference.execute(
                            "SELECT 1 FROM attempts WHERE model=? LIMIT 1", (model,)
                        ).fetchone()
                    ):
                        raise ValueError(
                            f"External model {model} duplicates a benchmark or submission model"
                        )
                    seen.add(model)
                if directory:
                    metrics, statuses, attribution = _read_quickstart_scores(
                        source, reference, truth, expected
                    )
                else:
                    metrics, statuses, attribution = _read_sqlite_scores(
                        external, cell, datasets, models, expected, truth, provenance
                    )
                for model in models:
                    scores = _validated_scores(model, expected, statuses, metrics)
                    classification_only = model == "OrionMoE-Small-v1" or (
                        provenance is not None and provenance.get("classification_only") is True
                    )
                    evaluations.append(
                        ExternalEvaluation(
                            model,
                            attribution,
                            classification_only,
                            source,
                            cell,
                            primary,
                            datasets,
                            scores,
                        )
                    )
    return evaluations


def _validated_scores(model, expected, statuses, metrics):
    scores = {}
    for row in metrics.itertuples(index=False):
        unit = (row.seed, row.key)
        if row.model != model or unit not in expected:
            continue
        score = row.f1_macro
        if (
            unit in scores
            or not isinstance(score, (int, float))
            or not math.isfinite(score)
            or not 0 <= score <= 1
        ):
            raise ValueError(f"Invalid or duplicate external Macro-F1 for {model} at {unit}")
        scores[unit] = score
    outcomes = {}
    for row in statuses.itertuples(index=False):
        unit = (row.seed, row.key)
        if row.model != model or unit not in expected:
            continue
        if (
            unit in outcomes
            or row.status not in {"pass", "fail"}
            or (unit in scores) != (row.status == "pass")
        ):
            raise ValueError(f"Missing score or incompatible outcome for {model} at {unit}")
        outcomes[unit] = scores.get(unit)
    if missing := expected - outcomes.keys():
        raise ValueError(
            f"External model {model} is missing {len(missing)} shared folds: {min(missing)}"
        )
    if not scores:
        raise ValueError(f"No passing shared folds for {model}")
    return pd.DataFrame(
        [
            {"model": model, "key": key, "seed": seed, "score": outcomes[seed, key]}
            for seed, key in sorted(expected)
        ]
    )


def rank_external_evaluation(
    evaluations: Sequence[ExternalEvaluation],
    datasets: set[str],
    classification: pd.DataFrame,
    hidden: list[str],
    n_boot: int,
) -> pd.DataFrame:
    """Rank visible configurations with a score for every contributed fold."""
    cell = evaluations[0].cell
    if "cell" in classification:
        classification = classification[classification["cell"].eq(cell)]
    scores = fold_scores(classification, None)
    keys = {f"{dataset}_0" for dataset in datasets}
    expected = {(seed, key) for seed in get_seeds(evaluations[0].config) for key in keys}
    scores = scores.loc[pd.MultiIndex.from_frame(scores[["seed", "key"]]).isin(expected)]
    fallback = scores.loc[scores["model"].eq("DUMMY")].set_index(["seed", "key"])["score"]
    scores = scores[~scores["model"].isin({*hidden, "AUTOGLUON", "DUMMY"})]
    complete = [
        model
        for model, rows in scores.groupby("model")
        if len(rows) == len(expected)
        and set(zip(rows["seed"], rows["key"], strict=True)) == expected
    ]
    if "RF" not in complete:
        raise ValueError("Random Forest lacks scores for the complete external comparison pool")
    contributions = []
    for evaluation in evaluations:
        selected = evaluation.scores[evaluation.scores["key"].isin(keys)].copy()
        if selected["score"].isna().all():
            raise ValueError(f"No passing folds on the common dataset pool for {evaluation.model}")
        missing = selected["score"].isna()
        selected.loc[missing, "score"] = fallback.reindex(
            pd.MultiIndex.from_frame(selected.loc[missing, ["seed", "key"]])
        ).to_numpy()
        if selected["score"].isna().any():
            raise ValueError(
                f"Constant-predictor scores are missing for failures of {evaluation.model}"
            )
        contributions.append(selected)
    combined = pd.concat(
        [scores[scores["model"].isin(complete)], *contributions], ignore_index=True
    )
    return compute_elo(combined, n_boot=n_boot)


def write_external_comparison(
    output: Path,
    evaluations: Sequence[ExternalEvaluation],
    classification: pd.DataFrame,
    dashboard: dict,
    n_boot: int,
    database: Path,
) -> None:
    meta = dashboard["meta"]
    if any(item.source.is_relative_to(output.resolve()) for item in evaluations):
        raise ValueError("Keep external submissions outside the deployable website directory")
    evaluation = evaluations[0]
    datasets = set.intersection(*(item.datasets for item in evaluations))
    if not datasets:
        raise ValueError("External models have no shared classification datasets")
    ranking = rank_external_evaluation(
        evaluations, datasets, classification, meta["plot_excluded_models"], n_boot
    )
    if missing := {item.model for item in evaluations} - set(ranking["model_id"]):
        raise ValueError(f"No shared-fold Elo rating for {', '.join(sorted(missing))}")
    index = output / "index.html"
    html = index.read_text(encoding="utf-8")
    anchor = '<p id="elo-overlap-warning"'
    if html.count(anchor) != 1:
        raise ValueError(f"Missing leaderboard callouts in {index}")
    folds = len(get_seeds(evaluation.config))
    count = len(datasets)
    config = evaluation.config
    features = config["bio_max_features"]
    samples = config["train_subsample"]
    feature_label = f"up to {features:,} features" if features is not None else "all features"
    sample_label = (
        f"up to {samples:,} training rows" if samples is not None else "all training rows"
    )
    dataset_label = "dataset" if count == 1 else "datasets"
    fold_label = "fold" if folds == 1 else "folds"
    scope = [
        f"Macro-F1 Elo · {count:,} shared classification {dataset_label}",
        f"{folds} {fold_label} each · {feature_label} · {sample_label}",
    ]
    external_models = {
        item.model: {
            "provenance": item.provenance,
            "classification_only": item.classification_only,
        }
        for item in evaluations
    }
    payload = json.dumps(
        {
            "cell": evaluation.cell,
            "models": external_models,
            "scope": [*scope, "Recorded failures use the constant predictor."],
            "rows": ranking.to_dict("records"),
        },
        separators=(",", ":"),
    ).replace("<", "\\u003c")
    controls = f"""{VIEW_START}
            <p id="external-elo-warning" class="model-card-limit-warning" hidden
               style="border-color: var(--red); color: var(--red); background: var(--surface);">
              <strong>External evaluations</strong> may be less reliable than reference results and may use different hardware.
            </p>
            <script type="application/json" id="external-elo-data">{payload}</script>
            {VIEW_END}
            """
    html = re.sub(rf"{VIEW_START}.*?{VIEW_END}\n[ \t]*", "", html, flags=re.DOTALL)
    html = re.sub(r'<p id="external-results-link"[^>]*>[^\n]*</p>\n[ \t]*', "", html)
    html = re.sub(r'\n[ \t]*<button id="external-elo-toggle"[^>]*>[^<]*</button>', "", html)
    toggle = (
        '<button id="external-elo-toggle" class="button" type="button" '
        'aria-pressed="false" aria-controls="elo-chart" disabled>'
        "Hide external models</button>"
    )
    html, updated = re.subn(
        r'(<button id="show-all-models"[^>]*>[^<]*</button>)',
        lambda match: match[1] + "\n            " + toggle,
        html,
    )
    if updated != 1:
        raise ValueError(f"Missing advanced model controls in {index}")
    html = html.replace(anchor, controls + anchor)
    app = Path(__file__).with_name("web") / WEB_APP
    app_bytes = app.read_bytes().replace(b"\r\n", b"\n")
    app_id = hashlib.sha256(app_bytes).hexdigest()[:12]
    html, updated = re.subn(r'(?<=src="js/app\.js)\?[^"]*', f"?v={app_id}", html)
    if updated != 1:
        raise ValueError(f"Missing leaderboard app script in {index}")
    deployed_app = output / WEB_APP
    if not deployed_app.is_file() or deployed_app.read_bytes() != app_bytes:
        with _atomic_path(deployed_app) as temporary:
            temporary.write_bytes(app_bytes)
    index.write_text(html, encoding="utf-8")
    _update_external_artifacts(output, [database], link_release=True)


def refresh_external_comparison(
    database: Path, external_inputs: Sequence[Path], output: Path, *, workers: int, n_boot: int
) -> None:
    """Add a comparison to an existing website built from the same main database."""
    dashboard_path = output / "data/dashboard.json"
    if not dashboard_path.is_file() or not (output / "index.html").is_file():
        raise ValueError(
            f"Build the main website before refreshing its external comparison: {output}"
        )
    dashboard = json.loads(dashboard_path.read_text(encoding="utf-8"))
    main_asset = next(row for row in dashboard["raw_exports"] if row["format"] == "sqlite3")
    if main_asset["sha256"] != sha256_file(database):
        raise ValueError("Existing website was built from a different main results database")
    meta = dashboard["meta"]
    cell = meta["reference_cell"]
    evaluations = load_external_evaluations(database, external_inputs, cell)
    cache = output.resolve().with_name(output.name + ".cache") / "fold_metrics.sqlite"
    _, frames, _, _ = read_inputs(database.resolve(), [cell], workers=workers, metric_cache=cache)
    write_external_comparison(
        output, evaluations, frames["strict"]["classification"], dashboard, n_boot, database
    )
    write_sitemaps(output, "https://" + meta["domain"], meta["snapshot_utc"][:10])


def remove_legacy_page(output: Path) -> None:
    page = output / LEGACY_PAGE
    if page.is_file() and GENERATED in page.read_text(encoding="utf-8"):
        page.unlink()


def clear_external_comparison(output: Path, database: Path) -> None:
    """Remove a previously generated comparison when the external input is omitted."""
    _update_external_artifacts(output, [database])


def _update_external_artifacts(
    output: Path, keep: Sequence[Path], *, link_release: bool = False
) -> None:
    remove_legacy_page(output)
    artifacts = output / "artifacts.html"
    if artifacts.is_file():
        html = artifacts.read_text(encoding="utf-8")
        cleaned = re.sub(rf'\n[ \t]*<a id="{DOWNLOAD_ID}(?:-\d+)?"[^\n]*</a>', "", html)
        if link_release:
            card = (
                f'<a id="{DOWNLOAD_ID}" class="data-file" href="{EXTERNAL_RESULTS_URL}">'
                "<span><strong>External evaluation results</strong>"
                "<span>Download from the GitHub release</span></span> "
                '<b aria-hidden="true">↓</b></a>'
            )
            cleaned, count = re.subn(
                r'(<div id="raw-files"[^>]*>.*?)\n( +</div>)',
                lambda match: f"{match[1]}\n          {card}\n{match[2]}",
                cleaned,
                count=1,
                flags=re.DOTALL,
            )
            if count != 1:
                raise ValueError(f"Missing download list in {artifacts}")
        if cleaned != html:
            artifacts.write_text(cleaned, encoding="utf-8")
    protected = {path.resolve() for path in keep}
    for download in (output / "data").glob("external-results*"):
        if re.fullmatch(r"external-results(?:-\d+)?\.(?:sqlite|zip)", download.name):
            if download.resolve() not in protected:
                download.unlink(missing_ok=True)
